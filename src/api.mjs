export const CONNECT_PATH = "/api/vscode-desktop-connect";

function json(value, status = 200) {
  return Response.json(value, {
    status,
    headers: { "cache-control": "no-store", "referrer-policy": "no-referrer" },
  });
}

/** The Connection carrier admits an authenticated owner before this exact route runs. */
export function createConnectHandler(
  connection,
  server,
  control = { read: () => ({ enabled: false, revision: 0 }) },
) {
  return async (request) => {
    request.signal.throwIfAborted();
    const { host, port, protocol } = server;
    if (
      !["127.0.0.1", "::1"].includes(host) ||
      !Number.isSafeInteger(port) ||
      port < 1 ||
      port > 65535 ||
      !["http:", "https:"].includes(protocol)
    )
      return json({ available: false, code: "LOCAL_HOST_UNAVAILABLE" }, 503);
    if (!["GET", "POST", "PATCH"].includes(request.method))
      return json({ code: "METHOD_NOT_ALLOWED" }, 405);
    if (request.method === "PATCH") {
      let value;
      try {
        const body = await request.text();
        request.signal.throwIfAborted();
        if (body.length > 1024) return json({ code: "INVALID_CONTROL" }, 400);
        value = JSON.parse(body);
      } catch {
        request.signal.throwIfAborted();
        return json({ code: "INVALID_CONTROL" }, 400);
      }
      if (
        !value ||
        typeof value !== "object" ||
        Array.isArray(value) ||
        Object.keys(value).length !== 2 ||
        typeof value.enabled !== "boolean" ||
        !Number.isSafeInteger(value.revision) ||
        value.revision < 0
      )
        return json({ code: "INVALID_CONTROL" }, 400);
      try {
        const state = await control.update(value.enabled, value.revision);
        return json({ available: true, ...state });
      } catch {
        request.signal.throwIfAborted();
        return json({ code: "CONTROL_UPDATE_FAILED" }, 409);
      }
    }
    try {
      const state = control.read();
      if (request.method === "GET") return json({ available: true, ...state });
      if (!state.enabled) return json({ code: "CONNECTION_DISABLED" }, 403);
      const body = await request.text();
      request.signal.throwIfAborted();
      if (body !== "") {
        if (body.length > 128) return json({ code: "INVALID_CONTROL" }, 400);
        let action;
        try { action = JSON.parse(body); } catch { return json({ code: "INVALID_CONTROL" }, 400); }
        if (action?.action !== "pair" || Object.keys(action).length !== 1)
          return json({ code: "INVALID_CONTROL" }, 400);
        const paired = await control.pair();
        request.signal.throwIfAborted();
        if (!control.read().enabled) return json({ code: "CONNECTION_DISABLED" }, 403);
        return json(paired);
      }
      // Called only by the person's Copy action. No token is generated by status reads.
      const target = await control.address?.() ?? server;
      if (target.host !== "127.0.0.1" && target.host !== "::1" || !Number.isSafeInteger(target.port) || target.port < 1 || target.port > 65535 || !["http:", "https:"].includes(target.protocol))
        throw new Error("Invalid local carrier");
      request.signal.throwIfAborted();
      if (!control.read().enabled) return json({ code: "CONNECTION_DISABLED" }, 403);
      const authority = target.host === "::1" ? "[::1]" : target.host;
      const base = `${target.protocol}//${authority}:${target.port}/`;
      const url = new URL(target.launchUrl ?? connection.authenticatedUrl(base));
      const tokens = url.searchParams.getAll("token");
      if (
        url.origin !== new URL(base).origin ||
        url.pathname !== "/" ||
        url.hash ||
        url.username ||
        url.password ||
        tokens.length !== 1 ||
        !tokens[0] ||
        tokens[0].length > 4096 ||
        /[\r\n\0]/u.test(tokens[0]) ||
        [...url.searchParams.keys()].some((key) => key !== "token")
      )
        throw new Error("Invalid connection address");
      return json({ url: url.href });
    } catch {
      // Never reflect an exception, origin or credential into an error or log.
      return json({ code: "CONNECTION_ADDRESS_UNAVAILABLE" }, 503);
    }
  };
}
